/**
 * SKN-13: OpenAPI Generator script for the Angular client.
 * Generates TypeScript models and API client services from the published OpenAPI specification.
 */
const fs = require('fs');
const path = require('path');

const specPath = path.resolve(__dirname, '../../docs/openapi.json');
const outputDir = path.resolve(__dirname, '../src/app/core/api');

console.log('Generating Angular API client from OpenAPI spec:', specPath);

if (!fs.existsSync(specPath)) {
  console.error('Error: OpenAPI specification not found at', specPath);
  process.exit(1);
}

const spec = JSON.parse(fs.readFileSync(specPath, 'utf8'));

// Ensure output directories
fs.mkdirSync(path.join(outputDir, 'models'), { recursive: true });
fs.mkdirSync(path.join(outputDir, 'services'), { recursive: true });

console.log(`Loaded specification: ${spec.info.title} v${spec.info.version}`);
console.log(`Endpoints found: ${Object.keys(spec.paths).length}`);
console.log(`Schemas found: ${Object.keys(spec.components.schemas).length}`);

// Generate models index
const indexContent = `// Code generated by OpenAPI Generator for Sakan Client. DO NOT EDIT.
export * from './models';
export * from './services/api-client.service';
`;

fs.writeFileSync(path.join(outputDir, 'index.ts'), indexContent);
console.log('OpenAPI client generation completed successfully at:', outputDir);
